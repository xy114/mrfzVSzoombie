export function createDefaultGrid() {
  var tiles = {};
  for (var r = 0; r < 5; r++) {
    for (var c = 0; c < 9; c++) {
      var x1 = c * 100, y1 = r * 108;
      var x2 = (c + 1) * 100, y2 = (r + 1) * 108;
      tiles[r+','+c] = {
        poly: [[x1, y1], [x2, y1], [x2, y2], [x1, y2]],
        center: [x1 + 50, y1 + 54],
      };
    }
  }
  return { rows: 5, cols: 9, tiles };
}
